import { access, mkdir, readFile, stat } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import path from "node:path";

const sourcePath = path.resolve(process.argv[2] ?? "input/e2e-generated.mp4");
const origin = process.env.APP_ORIGIN ?? "http://127.0.0.1:3000";
const timeoutAt = Date.now() + Number(process.env.E2E_TIMEOUT_MS ?? 180_000);

async function json(response: Response) {
  const body = await response.json();
  if (!response.ok) throw new Error(body.error?.message ?? `Request failed with ${response.status}`);
  return body;
}

async function main() {
  try { await access(sourcePath); } catch {
    if (process.argv[2]) throw new Error(`Input file not found: ${sourcePath}`);
    await mkdir(path.dirname(sourcePath), { recursive: true });
    console.log("Generating a deterministic 2-second 1280×720 test video with FFmpeg");
    await promisify(execFile)("ffmpeg", ["-hide_banner","-loglevel","error","-f","lavfi","-i","testsrc2=size=1280x720:rate=24","-t","2","-c:v","libx264","-pix_fmt","yuv420p","-y",sourcePath]);
  }
  const metadata = await stat(sourcePath);
  const filename = path.basename(sourcePath);
  console.log(`Uploading ${filename} (${metadata.size} bytes)`);
  const created = await json(await fetch(`${origin}/api/videos/uploads`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ filename, contentType: "video/mp4", sizeBytes: metadata.size }),
  }));
  const bytes = await readFile(sourcePath);
  const upload = await fetch(created.upload.url, { method: "PUT", headers: created.upload.headers, body: bytes });
  if (!upload.ok) throw new Error(`Object upload failed with ${upload.status}`);
  await json(await fetch(`${origin}/api${created.completeUrl}`, { method: "POST" }));
  console.log(`Queued video ${created.videoId}`);

  while (Date.now() < timeoutAt) {
    const video = await json(await fetch(`${origin}/api/videos/${created.videoId}`));
    console.log(`Status: ${video.status}`);
    if (video.status === "failed") throw new Error(video.error?.message ?? "Video processing failed");
    if (video.status === "completed") {
      const manifest = await fetch(`${origin}${video.playbackUrl}`);
      const master = await manifest.text();
      if (!manifest.ok || !master.startsWith("#EXTM3U")) throw new Error("Published HLS manifest is not playable");
      const renditions = [...master.matchAll(/^([^#].*\.m3u8)$/gm)].map((match) => match[1]!);
      if (renditions.length < 2) throw new Error("Master playlist does not contain both renditions");
      for (const rendition of renditions) {
        const response = await fetch(new URL(rendition, `${origin}${video.playbackUrl}`).toString());
        const playlist = await response.text();
        const segment = playlist.match(/^([^#].*\.ts)$/m)?.[1];
        if (!response.ok || !segment) throw new Error(`Rendition ${rendition} has no playable segment`);
        const segmentResponse = await fetch(new URL(segment, response.url).toString());
        if (!segmentResponse.ok) throw new Error(`Segment for ${rendition} is unavailable`);
      }
      await json(await fetch(`${origin}/api/social/videos/${created.videoId}`,{method:"PATCH",headers:{"content-type":"application/json"},body:JSON.stringify({title:"Frameflow E2E Film",description:"Generated by the local end-to-end verification.",tags:"e2e,ffmpeg,ai-video",visibility:"public"})}));
      const social = await fetch(`${origin}/api/social/videos/${created.videoId}`);
      if (!social.ok) throw new Error("Published video is missing from the social watch API");
      console.log(`PASS ${origin}/watch/${created.videoId}`);
      if (/^(1|true)$/i.test(process.env.E2E_CLEANUP ?? "")) await fetch(`${origin}/api/videos/${created.videoId}`,{method:"DELETE"});
      return;
    }
    await new Promise((resolve) => setTimeout(resolve, 2000));
  }
  throw new Error("Timed out waiting for video processing");
}

main().catch((error: unknown) => {
  console.error("E2E failed:", error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
